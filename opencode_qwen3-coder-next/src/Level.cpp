bool isSolidWall(int x, int z) {
    if (x < 0 || x >= MAP_WIDTH || z < 0 || z >= MAP_HEIGHT) return true;
    unsigned short tile = levelMap[z * MAP_WIDTH + x];
    return tile != TILE_EMPTY && tile != TILE_WALL_PLAIN;
}

bool isDoor(int x, int z) {
    if (x < 0 || x >= MAP_WIDTH || z < 0 || z >= MAP_HEIGHT) return false;
    unsigned short tile = levelMap[z * MAP_WIDTH + x];
    return tile == TILE_WALL_MAGAZIJN;
}
